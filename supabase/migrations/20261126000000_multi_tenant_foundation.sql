alter table public.invoices drop constraint if exists invoices_invoice_items_invoice_id_fkey;

do $$
declare
  table_name text;
begin
  foreach table_name in array array[
    'clients','products','invoices','invoice_items','payments','orders',
    'purchase_orders','purchase_order_items','quotations','quotation_items',
    'documents','suppliers','business_settings'
  ]
  loop
    execute format('alter table public.%I enable row level security', table_name);
    execute format('drop policy if exists "tenant select" on public.%I', table_name);
    execute format(
      'create policy "tenant select" on public.%I for select to authenticated using (is_organization_member(organization_id))',
      table_name
    );
    execute format('drop policy if exists "tenant insert" on public.%I', table_name);
    execute format(
      'create policy "tenant insert" on public.%I for insert to authenticated with check (is_organization_member(organization_id))',
      table_name
    );
    execute format('drop policy if exists "tenant update" on public.%I', table_name);
    execute format(
      'create policy "tenant update" on public.%I for update to authenticated using (is_organization_member(organization_id)) with check (is_organization_member(organization_id))',
      table_name
    );
    execute format('drop policy if exists "tenant delete" on public.%I', table_name);
    execute format(
      'create policy "tenant delete" on public.%I for delete to authenticated using (is_organization_member(organization_id))',
      table_name
    );
  end loop;
end;
$$;

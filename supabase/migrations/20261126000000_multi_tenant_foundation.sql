create extension if not exists pgcrypto;

create table if not exists public.organizations (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  slug text unique,
  workspace_mode text not null default 'business'
    check (workspace_mode in ('retail', 'business')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.organization_members (
  organization_id uuid not null references public.organizations(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  role text not null default 'owner'
    check (role in ('owner', 'admin', 'manager', 'cashier', 'viewer')),
  created_at timestamptz not null default now(),
  primary key (organization_id, user_id)
);

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  email text,
  display_name text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create or replace function public.is_organization_member(p_organization_id uuid)
returns boolean
language sql
stable
security invoker
set search_path = public
as $$
  select exists (
    select 1
    from organization_members
    where organization_id = p_organization_id
      and user_id = auth.uid()
  );
$$;

create or replace function public.ensure_current_organization()
returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare
  v_user_id uuid := auth.uid();
  v_org_id uuid;
  v_email text;
begin
  if v_user_id is null then
    raise exception 'Authentication required';
  end if;

  select organization_id
  into v_org_id
  from organization_members
  where user_id = v_user_id
  order by created_at
  limit 1;

  if v_org_id is not null then
    return v_org_id;
  end if;

  select coalesce(raw_user_meta_data->>'display_name', email)
  into v_email
  from auth.users
  where id = v_user_id;

  insert into organizations (name)
  values (coalesce(v_email, 'My iCanBill workspace'))
  returning id into v_org_id;

  insert into organization_members (organization_id, user_id, role)
  values (v_org_id, v_user_id, 'owner');

  insert into profiles (id, email)
  select v_user_id, email
  from auth.users
  where id = v_user_id
  on conflict (id) do update set email = excluded.email, updated_at = now();

  return v_org_id;
end;
$$;

grant execute on function public.ensure_current_organization() to authenticated;
grant execute on function public.is_organization_member(uuid) to authenticated;

create or replace function public.handle_new_auth_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (id, email)
  values (new.id, new.email)
  on conflict (id) do update
    set email = excluded.email,
        updated_at = now();
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute function public.handle_new_auth_user();

alter table public.organizations enable row level security;
alter table public.organization_members enable row level security;
alter table public.profiles enable row level security;

drop policy if exists "members read organizations" on public.organizations;
create policy "members read organizations" on public.organizations
for select to authenticated
using (is_organization_member(id));

drop policy if exists "owners update organizations" on public.organizations;
create policy "owners update organizations" on public.organizations
for update to authenticated
using (
  exists (
    select 1 from organization_members
    where organization_id = organizations.id
      and user_id = auth.uid()
      and role in ('owner', 'admin')
  )
);

drop policy if exists "members read memberships" on public.organization_members;
create policy "members read memberships" on public.organization_members
for select to authenticated
using (is_organization_member(organization_id));

drop policy if exists "users read own profile" on public.profiles;
create policy "users read own profile" on public.profiles
for select to authenticated
using (id = auth.uid());

drop policy if exists "users update own profile" on public.profiles;
create policy "users update own profile" on public.profiles
for update to authenticated
using (id = auth.uid());

